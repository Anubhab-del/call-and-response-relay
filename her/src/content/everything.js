function hash32(e) {
  let t = e + 2654435769;
  return (
    (t = Math.imul(t ^ (t >>> 16), 569420461)),
    (t = Math.imul(t ^ (t >>> 15), 1935289751)),
    (t ^ (t >>> 15)) >>> 0
  );
}

function shuffledOrder(e) {
  let t = Array.from(
    {
      length: e,
    },
    (e, t) => t,
  );
  for (let n = e - 1; n > 0; n--) {
    let e = hash32(n * 2654435761) % (n + 1),
      r = t[n];
    ((t[n] = t[e]), (t[e] = r));
  }
  return t;
}

